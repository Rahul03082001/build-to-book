#!/usr/bin/env python3
"""Require a Jira key at the start of every commit message.

Traceability from each change to a story is a compensating control for the
missing second approver (ADR-011). Merge and revert commits are exempt because
their messages are generated by Git.
"""

from __future__ import annotations

import pathlib
import re
import sys

PATTERN = re.compile(r"^BTB-\d+: .+")
EXEMPT_PREFIXES = ("Merge ", "Revert ", "fixup!", "squash!")


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("usage: check_commit_message.py <commit-msg-file>", file=sys.stderr)
        return 2

    message = pathlib.Path(argv[1]).read_text(encoding="utf-8")
    subject = next(
        (line for line in message.splitlines() if line.strip() and not line.startswith("#")),
        "",
    ).strip()

    if subject.startswith(EXEMPT_PREFIXES):
        return 0

    if not PATTERN.match(subject):
        print(
            f"Commit message must start with a Jira key, e.g.\n"
            f"  BTB-12: add goods receipt staging model\n\n"
            f"Got:\n  {subject!r}\n",
            file=sys.stderr,
        )
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
