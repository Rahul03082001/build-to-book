"""Generate the inventory slice: master data, purchasing, movements, postings.

This is the Phase 1 vertical slice (ADR-013). Seven extracts, shaped loosely
on SAP structures (ADR-002), all synthetic (ADR-001, ADR-019):

    materials                 material master
    suppliers                 vendor master
    standard_costs            effective-dated, so inventory revalues correctly
    purchase_order_headers    one row per PO
    purchase_order_lines      one row per PO item
    goods_movements           one row per material document line
    gl_postings               one row per accounting document line

Three invariants hold when defects are off, and each is asserted by a test
rather than hoped for:

1. **Every goods receipt references a real PO line.** Without this the
   three-way match has nothing to match.
2. **On-hand never goes negative.** Issues are generated by walking each
   material's receipts in posting-date order and consuming only what is
   actually on hand at that moment.
3. **The subledger ties to the GL.** Every movement posts to the inventory
   account at the standard cost in force on its posting date, so
   `sum(goods_movements.amount_usd)` equals the net movement on account
   130000 for the same period, to the cent.

Valuation uses the cost in force on the **posting date**, not the document
date (docs/metric_definitions.md). A mid-period cost change therefore values
earlier movements at the old cost and later ones at the new -- which is the
behaviour the SCD Type 2 snapshot in Phase 3 has to reproduce.
"""

