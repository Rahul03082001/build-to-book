def _month_ends(period_start: dt.date, months: int) -> list[dt.date]:
    """Last calendar day of each period in the window."""
    out: list[dt.date] = []
    year, month = period_start.year, period_start.month
    for _ in range(months):
        nxt = dt.date(year + 1, 1, 1) if month == 12 else dt.date(year, month + 1, 1)
        out.append(nxt - dt.timedelta(days=1))
        year, month = nxt.year, nxt.month
    return out


def _period_bounds(profile: Profile) -> tuple[dt.date, dt.date]:
    ends = _month_ends(profile.period_start, profile.months)
    return profile.period_start, ends[-1]


class InventoryGenerator:
    """Deterministic generator for the inventory slice.

    The same seed produces byte-identical extracts. Every random draw goes
    through one seeded NumPy generator, in a fixed order, so determinism does
    not depend on dict iteration or on when a value happens to be needed.
    """

    def __init__(self, config: GeneratorConfig, profile_name: str) -> None:
        self.config = config
        self.profile = config.profile(profile_name)
        self.rng = np.random.default_rng(config.seed)
        self.start, self.end = _period_bounds(self.profile)
        self.month_ends = _month_ends(self.profile.period_start, self.profile.months)

        self._material_numbers = ids.material_numbers()
        self._supplier_numbers = ids.supplier_numbers()
        self._po_numbers = ids.purchase_order_numbers()
        # One material-document and accounting-document range per fiscal year,
        # because those numbers are unique within a year, not globally.
        self._md_numbers: dict[int, ids.NumberRange] = {}
        self._ad_numbers: dict[int, ids.NumberRange] = {}
        self._rv_numbers: dict[int, ids.NumberRange] = {}
        self._standard_cost_rows: list[dict[str, Any]] = []

    # -- helpers ----------------------------------------------------------
    def _choice(self, options: Sequence[Any]) -> Any:
        return options[int(self.rng.integers(0, len(options)))]

    def _date_between(self, first: dt.date, last: dt.date) -> dt.date:
        span = (last - first).days
        if span <= 0:
            return first
        return first + dt.timedelta(days=int(self.rng.integers(0, span + 1)))

    def _md_range(self, year: int) -> ids.NumberRange:
        if year not in self._md_numbers:
            self._md_numbers[year] = ids.material_document_numbers()
        return self._md_numbers[year]

    def _ad_range(self, year: int) -> ids.NumberRange:
        if year not in self._ad_numbers:
            self._ad_numbers[year] = ids.accounting_document_numbers()
        return self._ad_numbers[year]

    def _rv_range(self, year: int) -> ids.NumberRange:
        if year not in self._rv_numbers:
            self._rv_numbers[year] = ids.revaluation_document_numbers()
        return self._rv_numbers[year]

    # -- master data ------------------------------------------------------
    def materials(self) -> list[dict[str, Any]]:
        groups = list(self.config.domain["material_groups"])
        rows: list[dict[str, Any]] = []
        created_floor = self.start - dt.timedelta(days=720)
        for index in range(self.profile.materials):
            group = groups[index % len(groups)]
            descriptor = self._choice(_DESCRIPTORS[group])
            rows.append(
                {
                    "material_number": self._material_numbers.next(),
                    "material_description": descriptor,
                    "material_group": group,
                    "base_uom": self.config.domain["uom_default"],
                    "plant": PLANT,
                    "created_on": self._date_between(created_floor, self.start),
                }
            )
        return rows

    def suppliers(self) -> list[dict[str, Any]]:
        created_floor = self.start - dt.timedelta(days=1460)
        rows: list[dict[str, Any]] = []
        for index in range(self.profile.suppliers):
            number = self._supplier_numbers.next()
            rows.append(
                {
                    "supplier_number": number,
                    # Deliberately synthetic names. No real supplier appears.
                    "supplier_name": f"SYNTH COMPONENTS {index + 1:02d} LTD",
                    "country": self._choice(_COUNTRIES),
                    "payment_terms": self._choice(_PAYMENT_TERMS),
                    "created_on": self._date_between(created_floor, self.start),
                }
            )
        return rows

    def standard_costs(
        self, materials: Sequence[dict[str, Any]]
    ) -> tuple[list[dict[str, Any]], dict[str, list[tuple[dt.date, dt.date, decimal.Decimal]]]]:
        """Effective-dated standard costs.

        Roughly one material in six gets a mid-period change, so the as-of join
        and the Phase 3 SCD Type 2 snapshot have something real to reproduce. A
        material with a single cost for the whole window would make an as-of
        bug invisible.

        Returns:
            The extract rows, and a lookup of
            ``material_number -> [(valid_from, valid_to, cost)]`` for valuation.
        """
        far_future = dt.date(9999, 12, 31)
        rows: list[dict[str, Any]] = []
        lookup: dict[str, list[tuple[dt.date, dt.date, decimal.Decimal]]] = {}

        for material in materials:
            number = material["material_number"]
            low, high = MATERIAL_GROUP_PRICE_BANDS[material["material_group"]]
            base = money(D(int(self.rng.integers(low, high + 1))))

            changes_mid_period = bool(self.rng.random() < 0.17)
            if not changes_mid_period:
                rows.append(
                    {
                        "material_number": number,
                        "valid_from": self.start,
                        "valid_to": far_future,
                        "standard_cost_usd": base,
                        "currency": CURRENCY,
                        "approved_by": self._choice(COST_APPROVERS),
                        "approved_on": self.start - dt.timedelta(days=7),
                    }
                )
                lookup[number] = [(self.start, far_future, base)]
                continue

            # Change lands on a period boundary, which is when a real standard
            # cost revision takes effect.
            boundary = self.month_ends[int(self.rng.integers(0, max(1, len(self.month_ends) - 1)))]
            change_date = boundary + dt.timedelta(days=1)
            factor = D("1") + (D(int(self.rng.integers(-1200, 1800))) / D("10000"))
            revised = money(base * factor)

            rows.append(
                {
                    "material_number": number,
                    "valid_from": self.start,
                    "valid_to": boundary,
                    "standard_cost_usd": base,
                    "currency": CURRENCY,
                    "approved_by": self._choice(COST_APPROVERS),
                    "approved_on": self.start - dt.timedelta(days=7),
                }
            )
            rows.append(
                {
                    "material_number": number,
                    "valid_from": change_date,
                    "valid_to": far_future,
                    "standard_cost_usd": revised,
                    "currency": CURRENCY,
                    "approved_by": self._choice(COST_APPROVERS),
                    "approved_on": change_date - dt.timedelta(days=3),
                }
            )
            lookup[number] = [
                (self.start, boundary, base),
                (change_date, far_future, revised),
            ]

        # Kept so inventory_revaluations() can attribute each change to the
        # approver who authorised it -- CTRL-007 joins the two.
        self._standard_cost_rows = rows
        return rows, lookup

    def period_close_date(self, posting_date: dt.date) -> dt.date:
        """When the period containing a date locks.

        ``close_lag_days`` after period end. Approximated as calendar days
        rather than business days: the generator only needs a stable boundary
        for the control to test against, and a real close calendar arrives with
        the finance extracts in Phase 2.
        """
        lag = int(self.config.close_calendar["close_lag_days"])
        first_of_next = (
            dt.date(posting_date.year + 1, 1, 1)
            if posting_date.month == 12
            else dt.date(posting_date.year, posting_date.month + 1, 1)
        )
        period_end = first_of_next - dt.timedelta(days=1)
        return period_end + dt.timedelta(days=lag)

    @staticmethod
    def cost_on(
        lookup: dict[str, list[tuple[dt.date, dt.date, decimal.Decimal]]],
        material_number: str,
        on: dt.date,
    ) -> decimal.Decimal:
        """Standard cost in force on a date (an as-of lookup).

        Valuation is by posting date, so this is the single place that decides
        what a movement is worth. The GL postings use the same function, which
        is why the subledger ties to the GL by construction rather than by
        coincidence.
        """
        for valid_from, valid_to, cost in lookup[material_number]:
            if valid_from <= on <= valid_to:
                return cost
        raise KeyError(f"no standard cost for {material_number} on {on.isoformat()}")

    # -- purchasing -------------------------------------------------------
    def purchase_orders(
        self,
        materials: Sequence[dict[str, Any]],
        suppliers: Sequence[dict[str, Any]],
    ) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
        """Purchase order headers and lines, in SAP's header/line split.

        The split is the point: a count of purchase orders and a count of
        purchase order lines are different numbers, and any metric over them
        has to say which grain it means.
        """
        target_lines = self.profile.purchase_order_lines
        headers: list[dict[str, Any]] = []
        lines: list[dict[str, Any]] = []

        # Order window stops short of period end so deliveries land inside it.
        order_last = self.end - dt.timedelta(days=20)

        while len(lines) < target_lines:
            po_number = self._po_numbers.next()
            supplier = self._choice(suppliers)
            po_date = self._date_between(self.start, order_last)

            line_count = min(int(self.rng.integers(1, 5)), target_lines - len(lines))
            headers.append(
                {
                    "po_number": po_number,
                    "supplier_number": supplier["supplier_number"],
                    "po_date": po_date,
                    "currency": CURRENCY,
                    "created_by": self._choice(_BUYERS),
                    "company_code": COMPANY_CODE,
                }
            )

            for item in ids.line_items(line_count):
                material = self._choice(materials)
                low, high = MATERIAL_GROUP_PRICE_BANDS[material["material_group"]]
                quantity = int(self.rng.integers(2, 41))
                unit_price = money(D(int(self.rng.integers(low, high + 1))))
                lines.append(
                    {
                        "po_number": po_number,
                        "po_item": item,
                        "material_number": material["material_number"],
                        "quantity_ordered": quantity,
                        "unit_price_usd": unit_price,
                        "net_value_usd": money(unit_price * quantity),
                        "uom": self.config.domain["uom_default"],
                        "delivery_date": self._date_between(
                            po_date + dt.timedelta(days=7),
                            min(po_date + dt.timedelta(days=45), self.end),
                        ),
                        "plant": PLANT,
                    }
                )

        return headers, lines

    # -- goods movements --------------------------------------------------
    def goods_movements(
        self,
        po_lines: Sequence[dict[str, Any]],
        cost_lookup: dict[str, list[tuple[dt.date, dt.date, decimal.Decimal]]],
    ) -> list[dict[str, Any]]:
        """Goods receipts against PO lines, then issues that never oversell.

        Receipts come first and are grouped into material documents by
        (PO, posting date), so a document can carry several items. That matters
        for the grain story: with one item per document, "one row per material
        document" and "one row per material document line" would be the same
        number and `fct_goods_movements`'s declared grain would prove nothing.

        Issues are generated by walking each material's receipts in posting
        order and consuming only what is on hand at that point, so on-hand
        cannot go negative. Phase 2's `negative_on_hand` defect works by
        deliberately breaking that ordering.
        """
        # --- receipts, one or two per PO line (partial deliveries happen) ---
        raw_receipts: list[dict[str, Any]] = []
        for line in po_lines:
            # A small share of ordered lines are never delivered inside the
            # window, which is what makes the PO/receipt join an outer join in
            # real reporting rather than an inner one.
            if self.rng.random() < 0.12:
                continue

            ordered = int(line["quantity_ordered"])

            # A share of lines are delivered short and closed short: the
            # supplier shipped less than ordered and the balance is never
            # coming. Without this, every receipted line is delivered in full,
            # so an invoice billing the received quantity and one billing the
            # ordered quantity are indistinguishable -- and the three-way
            # match's quantity leg can never be exercised. Found by a test
            # asserting the two differ somewhere.
            delivered = ordered
            if ordered >= 4 and self.rng.random() < SHORT_DELIVERY_RATE:
                delivered = ordered - int(self.rng.integers(1, max(2, ordered // 3)))

            splits = 2 if (delivered >= 6 and self.rng.random() < 0.22) else 1
            if splits == 2:
                first = int(self.rng.integers(1, delivered))
                quantities = [first, delivered - first]
            else:
                quantities = [delivered]

            delivery = line["delivery_date"]
            for offset_index, quantity in enumerate(quantities):
                # Deliveries slip; later splits land later.
                slip = int(self.rng.integers(-2, 9)) + offset_index * int(self.rng.integers(1, 12))
                posting = delivery + dt.timedelta(days=slip)
                posting = max(self.start, min(posting, self.end))
                raw_receipts.append(
                    {
                        "po_number": line["po_number"],
                        "po_item": line["po_item"],
                        "material_number": line["material_number"],
                        "quantity": quantity,
                        "posting_date": posting,
                        # Document date is when the paperwork was raised;
                        # posting date is when it hit the books. Reporting uses
                        # posting date (docs/metric_definitions.md).
                        "document_date": posting - dt.timedelta(days=int(self.rng.integers(0, 3))),
                    }
                )

        # --- issues, bounded by on-hand at the moment of issue ---
        by_material: dict[str, list[dict[str, Any]]] = {}
        for receipt in raw_receipts:
            by_material.setdefault(receipt["material_number"], []).append(receipt)

        # Issue volume is derived from the number of receipts, not from the
        # configured gl_postings figure. Deriving it from postings produced
        # ~8.5 issues per receipt on the full profile, which drained every
        # material to exactly zero closing stock -- arithmetically valid and
        # commercially nonsense.
        issues_target = int(len(raw_receipts) * float(self.config.domain["issues_per_receipt"]))
        receipt_total = max(1, len(raw_receipts))

        raw_issues: list[dict[str, Any]] = []
        for material_number in sorted(by_material):
            receipts = sorted(by_material[material_number], key=lambda r: r["posting_date"])
            quota = round(issues_target * len(receipts) / receipt_total)
            if quota <= 0:
                continue

            on_hand = 0
            received_total = 0
            emitted = 0
            for index, receipt in enumerate(receipts):
                on_hand += receipt["quantity"]
                received_total += receipt["quantity"]
                # Keep a floor of stock on hand. A manufacturer holds weeks of
                # supply; without this, a long window issues everything it
                # receives and closing inventory -- the headline KPI of this
                # slice -- is zero.
                floor = int(received_total * float(self.config.domain["inventory_retention"]))
                window_end = (
                    receipts[index + 1]["posting_date"] if index + 1 < len(receipts) else self.end
                )

                remaining_receipts = len(receipts) - index
                share = max(1, round((quota - emitted) / max(1, remaining_receipts)))
                for _ in range(share):
                    if emitted >= quota or on_hand <= floor:
                        break
                    issuable = on_hand - floor
                    if issuable <= 0:
                        break
                    ceiling = max(1, int(issuable * 0.55))
                    quantity = int(self.rng.integers(1, ceiling + 1))
                    posting = self._date_between(receipt["posting_date"], window_end)
                    raw_issues.append(
                        {
                            "material_number": material_number,
                            "quantity": quantity,
                            "posting_date": posting,
                            "document_date": posting,
                        }
                    )
                    on_hand -= quantity
                    emitted += 1

        # --- assemble material documents ---
        # Document numbers rise with posting date, as they do in a real system.
        receipt_groups: dict[tuple[str, dt.date], list[dict[str, Any]]] = {}
        for receipt in raw_receipts:
            receipt_groups.setdefault((receipt["po_number"], receipt["posting_date"]), []).append(
                receipt
            )

        documents: list[tuple[dt.date, str, list[dict[str, Any]]]] = [
            (posting_date, MVT_GOODS_RECEIPT, items)
            for (_po, posting_date), items in receipt_groups.items()
        ]
        documents.extend((issue["posting_date"], MVT_GOODS_ISSUE, [issue]) for issue in raw_issues)
        documents.sort(key=lambda entry: (entry[0], entry[1]))

        rows: list[dict[str, Any]] = []
        for posting_date, movement_type, items in documents:
            fiscal_year = posting_date.year
            document = self._md_range(fiscal_year).next()
            sign = MOVEMENT_SIGN[movement_type]
            for item_index, item in enumerate(items, start=1):
                cost = self.cost_on(cost_lookup, item["material_number"], posting_date)
                rows.append(
                    {
                        "material_document": document,
                        "material_document_item": item_index,
                        "fiscal_year": fiscal_year,
                        "movement_type": movement_type,
                        "material_number": item["material_number"],
                        "plant": PLANT,
                        "quantity": sign * item["quantity"],
                        "uom": self.config.domain["uom_default"],
                        # Valued at the standard cost in force on the posting
                        # date. The GL postings use the same lookup, which is
                        # why the subledger ties to the GL by construction.
                        "amount_usd": money(cost * item["quantity"] * sign),
                        "posting_date": posting_date,
                        "document_date": item["document_date"],
                        "po_number": item.get("po_number"),
                        "po_item": item.get("po_item"),
                        "entered_by": self._choice(_CLERKS),
                    }
                )
        return rows

    # -- standard cost revaluation ---------------------------------------
    def inventory_revaluations(
        self,
        movements: Sequence[dict[str, Any]],
        cost_lookup: dict[str, list[tuple[dt.date, dt.date, decimal.Decimal]]],
    ) -> list[dict[str, Any]]:
        """Revalue on-hand inventory when a standard cost changes.

        Standard costing values every movement at the standard in force on its
        posting date. That means inventory bought at the old cost and issued at
        the new one leaves a residue: the quantity nets to zero while the value
        does not. Left unposted, the inventory account drifts away from
        quantity x standard cost, and over a year of cost changes it can even
        go negative while every physical quantity stays correct -- which is
        exactly what the full profile showed before this existed.

        Real standard costing handles it by revaluing stock on hand when the
        cost changes and posting the difference to a price-difference account.
        That is what this does, so the invariant becomes exact:

            inventory GL balance == on-hand quantity x current standard cost

        The revaluation is value-only: quantity is untouched, because nothing
        physically moved.
        """
        # Prefix sums per material, so on-hand before a date is a bisect rather
        # than a scan. The full profile has ~160k movements across 300
        # materials; a scan per cost change would be quadratic.
        timeline: dict[str, tuple[list[dt.date], list[int]]] = {}
        grouped: dict[str, list[dict[str, Any]]] = {}
        for movement in movements:
            grouped.setdefault(movement["material_number"], []).append(movement)
        for material_number, rows in grouped.items():
            ordered = sorted(rows, key=lambda m: m["posting_date"])
            dates = [m["posting_date"] for m in ordered]
            running = 0
            cumulative: list[int] = []
            for movement in ordered:
                running += movement["quantity"]
                cumulative.append(running)
            timeline[material_number] = (dates, cumulative)

        def on_hand_before(material_number: str, when: dt.date) -> int:
            entry = timeline.get(material_number)
            if entry is None:
                return 0
            dates, cumulative = entry
            index = bisect.bisect_left(dates, when)
            return cumulative[index - 1] if index > 0 else 0

        approvals = {
            (row["material_number"], row["valid_from"]): row["approved_by"]
            for row in self._standard_cost_rows
        }

        rows_out: list[dict[str, Any]] = []
        for material_number in sorted(cost_lookup):
            windows = cost_lookup[material_number]
            for (_prev_from, _prev_to, old_cost), (new_from, _nt, new_cost) in itertools.pairwise(
                windows
            ):
                quantity = on_hand_before(material_number, new_from)
                if quantity <= 0:
                    continue
                amount = money((new_cost - old_cost) * quantity)
                if amount == 0:
                    continue
                fiscal_year = new_from.year
                rows_out.append(
                    {
                        "revaluation_document": self._rv_range(fiscal_year).next(),
                        "fiscal_year": fiscal_year,
                        "material_number": material_number,
                        "posting_date": new_from,
                        "old_standard_cost_usd": old_cost,
                        "new_standard_cost_usd": new_cost,
                        "quantity_on_hand": quantity,
                        "amount_usd": amount,
                        "currency": CURRENCY,
                        "approved_by": approvals.get((material_number, new_from), ""),
                    }
                )
        return rows_out

    # -- accounting -------------------------------------------------------
    def gl_postings(
        self,
        movements: Sequence[dict[str, Any]],
        revaluations: Sequence[dict[str, Any]] = (),
    ) -> list[dict[str, Any]]:
        """One accounting document per material document, two lines per item.

        A goods receipt debits inventory and credits the GR/IR clearing
        account. A goods issue credits inventory and debits consumption. Every
        document balances to zero in signed terms, and the inventory lines sum
        to the same figure as the movements that produced them.
        """
        by_document: dict[tuple[str, int], list[dict[str, Any]]] = {}
        for movement in movements:
            key = (movement["material_document"], movement["fiscal_year"])
            by_document.setdefault(key, []).append(movement)

        rows: list[dict[str, Any]] = []
        for (material_document, fiscal_year), items in sorted(
            by_document.items(), key=lambda kv: (kv[0][1], kv[0][0])
        ):
            accounting_document = self._ad_range(fiscal_year).next()
            line_item = 0
            for movement in sorted(items, key=lambda m: m["material_document_item"]):
                amount = abs(movement["amount_usd"])
                is_receipt = movement["movement_type"] == MVT_GOODS_RECEIPT
                offset_account = ACCOUNT_GR_IR_CLEARING if is_receipt else ACCOUNT_CONSUMPTION

                # Inventory line, then its offset.
                pairs = [
                    (
                        ACCOUNT_INVENTORY,
                        DEBIT if is_receipt else CREDIT,
                        movement["material_number"],
                    ),
                    (offset_account, CREDIT if is_receipt else DEBIT, None),
                ]
                for account, indicator, material_number in pairs:
                    line_item += 1
                    rows.append(
                        {
                            "accounting_document": accounting_document,
                            "line_item": line_item,
                            "fiscal_year": fiscal_year,
                            "company_code": COMPANY_CODE,
                            "gl_account": account,
                            "debit_credit_indicator": indicator,
                            "amount_usd": amount,
                            # Signed so a period's net movement is a plain sum:
                            # debits positive, credits negative.
                            "signed_amount_usd": amount if indicator == DEBIT else money(-amount),
                            "currency": CURRENCY,
                            "posting_date": movement["posting_date"],
                            "document_date": movement["document_date"],
                            # Entered on or just after the posting date, and
                            # always before the period closes -- clean data
                            # contains no backdated entry.
                            "entered_on": min(
                                movement["posting_date"]
                                + dt.timedelta(days=int(self.rng.integers(0, 3))),
                                self.period_close_date(movement["posting_date"]),
                            ),
                            "reference_document": material_document,
                            "material_number": material_number,
                            "entered_by": movement["entered_by"],
                        }
                    )

        # Revaluations post value only. A cost increase debits inventory and
        # credits the price-difference account; a decrease does the reverse.
        for revaluation in revaluations:
            fiscal_year = revaluation["fiscal_year"]
            accounting_document = self._ad_range(fiscal_year).next()
            amount = abs(revaluation["amount_usd"])
            increased = revaluation["amount_usd"] > 0
            pairs = [
                (
                    ACCOUNT_INVENTORY,
                    DEBIT if increased else CREDIT,
                    revaluation["material_number"],
                ),
                (ACCOUNT_INVENTORY_REVALUATION, CREDIT if increased else DEBIT, None),
            ]
            for line_item, (account, indicator, material_number) in enumerate(pairs, start=1):
                rows.append(
                    {
                        "accounting_document": accounting_document,
                        "line_item": line_item,
                        "fiscal_year": fiscal_year,
                        "company_code": COMPANY_CODE,
                        "gl_account": account,
                        "debit_credit_indicator": indicator,
                        "amount_usd": amount,
                        "signed_amount_usd": amount if indicator == DEBIT else money(-amount),
                        "currency": CURRENCY,
                        "posting_date": revaluation["posting_date"],
                        "document_date": revaluation["posting_date"],
                        "entered_on": revaluation["posting_date"],
                        "reference_document": revaluation["revaluation_document"],
                        "material_number": material_number,
                        "entered_by": "MLEDGER",
                    }
                )
        return rows

    # -- defect injection -------------------------------------------------
    def inject_defects(
        self, data: InventoryData, enabled: Sequence[str]
    ) -> list[defects.InjectedRecord]:
        """Plant the requested defects and return what was planted.

        Runs after the clean data is complete and internally consistent, so a
        defect is a deliberate deviation from a known-good baseline rather
        than an artefact of generation order. Injectors run in registry order
        for determinism.

        An unimplemented defect raises rather than being skipped: silently
        ignoring a requested defect would make a detection test pass with
        nothing planted.
        """
        planted: list[defects.InjectedRecord] = []
        for key in defects.REGISTRY:
            if key not in enabled:
                continue
            spec = self.config.defects[key]
            injector = defects.injector_for(key)
            count = int(spec.get("count", 1))

            if key == "duplicate_goods_receipt":
                planted.extend(injector(data.goods_movements, data.gl_postings, count, self.rng))
            elif key == "backdated_gl_posting":
                planted.extend(
                    injector(
                        data.gl_postings,
                        count,
                        self.period_close_date,
                        lambda year: self._ad_range(year).next(),
                        self.rng,
                    )
                )
            else:  # pragma: no cover - guarded by injector_for above
                raise NotImplementedError(
                    f"{key} has an injector but generate() does not know how to call it"
                )
        return planted

    # -- orchestration ----------------------------------------------------
    def generate(self) -> InventoryData:
        """Generate every inventory extract, in a fixed order."""
        materials = self.materials()
        suppliers = self.suppliers()
        standard_costs, cost_lookup = self.standard_costs(materials)
        headers, lines = self.purchase_orders(materials, suppliers)
        movements = self.goods_movements(lines, cost_lookup)
        revaluations = self.inventory_revaluations(movements, cost_lookup)
        postings = self.gl_postings(movements, revaluations)
        return InventoryData(
            materials=materials,
            suppliers=suppliers,
            standard_costs=standard_costs,
            purchase_order_headers=headers,
            purchase_order_lines=lines,
            goods_movements=movements,
            inventory_revaluations=revaluations,
            gl_postings=postings,
            cost_windows=cost_lookup,
        )
